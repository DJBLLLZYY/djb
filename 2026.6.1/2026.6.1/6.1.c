/*                                      浮点数在内存中的存储                   */
/*
* 任意一个二进制浮点数v可以表示成下面的形式：
* （-1）^S*M*2^E
* (-1)^S表示符号位，当S=0，V为正数；当S=1，V为负数
* M表示有效数字，大于等于1，小于2
* 2^E表示指数位
* 例如：
*      V=9.5（十进制）=1001.1（小数点后面为2^(-1),2^(-2)以此类推）
*       =1.0011*2^3
*		=(-1)^0 * 1.0011 * 2 ^ 3
*	   S=0,M=1.0011,E=3
* 
* 
*      V=9.6 难以凑出2进制表示，难以获得0.6，因此浮点数运算会有误差
*		
* 
* 
* IEEE754规定：
*	对于32位的浮点数，最高位的1为是符号位S，接着的8位是指数E， 剩下的23位为有效数字M
*	对于64位的浮点数，最高位的1为是符号位S，接着的11位是指数E，剩下的52位为有效数字M
* 
* 在计算机内部保存M时，默认是1，因此可以被舍去，只保存后面的小数部分，这样在32位时M就可以有24位
* 至于指数E，E为无符号整数（大于等于0），E如果是8位，取值范围是0-255，E如果是11位，取值范围是0-2047
  但是科学计数法中，E可以是负数，所以存入内存是的E的真实值必须再加上一个中间数，对于8位的E，这个数是127，
  对于11位的E，这个中间值是1023，比如2^10的E是10，所以保存成32为浮点数时，必须保存成10+127=137，即10001001

  指数E从内存中取出分成三种情况：
  E不为全0或者全1时：指数E的计算值减去127或者1023得到真实值
  E为全0，（这时，真实的E可能为-127，真实的数是10^(-127),无限接近0）
     这时浮点数的指数E等于1-127或者1-1023即为真实值，有效数字M不再加上第一位的1，直接还原为0.xxx的小数
  E为全1，（E的真实值为128，此时真实值为10^128量级，非常大，表示为无穷大）
	 这是，如果有效数字M全为0，表示+-无穷大


*/



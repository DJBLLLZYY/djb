
 /*                          数据在内存中的存储            */
/*
* 整数的二进制有三种表示形式：
* 1.正整数的原码，反码，补码相同
* 2.负整数的原码，反码，补码需要计算
* 原码：直接通过正负的形式写出的二进制序列就是原码
* 反码：原码的符号位不变，其他位按位取反得到反码
* 补码：反码+1就是补码
* 整数内存中存放的是补码的二进制序列
* 对于整形来说，内存中存储数据以补码的形式存储
* 因为在计算机系统中，数值一律用补码来表示和存储，使用补码，可以将符号位和数值域统一处理
* 同时，加法和减法也可以统一处理（CPU只有加法器）此外，补码与原码互相转换，其运算过程是相同的，
  不需要额外的硬件电路
*/


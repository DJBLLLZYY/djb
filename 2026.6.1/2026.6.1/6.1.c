//有符号型存储的是补码，计算具体值时要转换成原码
//无符号型存储的是大于等于0，存储的是补码就是原码
int main()
{
	char a = -1;
	//a的原码1000 0000 0000 0000 0000 0000 0000 0001
	//   反码1111 1111 1111 1111 1111 1111 1111 1110
	//   补码1111 1111 1111 1111 1111 1111 1111 1111
	//char大小为一个字节，截断最小的八位，则a是1111 1111
	//%d打印的是有符号整形，对a要整形提升（有符号高位补符号位，无符号高位补0）
	//整形提升后 1111 1111 1111 1111 1111 1111 1111 1111（仍是补码）
	//反码 1111 1111 1111 1111 1111 1111 1111 1110
	//原码 1000 0000 0000 0000 0000 0000 0000 0001 （结果是-1）
	signed char b = -1;
	unsigned char c = -1;
	printf("a=%d,b=%d,c=%d", a, b, c);
	char d = -128;
	//1000 0000 0000 0000 0000 0000 1000 0000 原码
	//1111 1111 1111 1111 1111 1111 0111 1111  反码
	//1111 1111 1111 1111 1111 1111 1000 0000 补码 d为char型，截断后八位
	//1000 0000 d,d为有符号，整形提升为
	//1111 1111 1111 1111 1111 1111 1000 0000（在内存中实际存放的）
	printf("%u", d); // %u打印的是无符号数，认为内存中的是无符号数
	printf("%d", d); //%d打印时内存认为是有符号数，存的是补码 1111 1111 1111 1111 1111 1111 1000 0000
	return 0;
}


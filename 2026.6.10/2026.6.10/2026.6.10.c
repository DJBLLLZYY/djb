/*                         联合(共用体)                */
//联合的特征是成员共用一块空间，联合体变量的大小至少是最小成员的大小，各个成员不能同时使用

union Un
{
    //例如此时，改c的时候i会改变，改i的时候c会改变
    char c;//一个字节
    int i;//四个字节
    char arr[5];//对齐数是1
    //联合体最大的对齐数是4，其内存的大小是4的倍数，大小是8
};

int main()
{
    union Un u;
    printf("%d\n", sizeof(u));
    printf("%p\n", &u);
    printf("%p\n", &(u.c));
    printf("%p\n", &(u.i)); //这三个地址是一样的
    return 0;
}
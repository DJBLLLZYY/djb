//为什么存在内存对齐：
/*
   1.平台原因：不是所有的硬件平台都能访问任意地址上的任意数据的，某些硬件平台只能在某些地址处取某些特定
     类型的数据，否则抛出硬件异常
   2.性能原因：数据结构（尤其是栈）应该尽可能的在自然边界上对齐，原因在于，为了访问未对齐的内存，处理器需要作两次
     内存访问，而对齐的内存访问仅需要一次访问。
	 总体来说，结构体的内存对齐是拿空间换时间的做法
*/









